    cpu.pc += 1;
    cpu.cycle(8);
    cpu.write_byte(crate::defs::R_VDMA_LEN as u16, cpu.a);
    cpu.pc += 2;
    cpu.cycle(12);
    cpu.a = 0;
    cpu.flag_z = true;
    cpu.flag_n = false;
    cpu.flag_h = false;
    cpu.flag_c = false;
