    cpu.cycle(8);
    cpu.a = cpu.read_byte(0xc6f5);
    cpu.pc += 3;
    cpu.cycle(16);
    let value = cpu.b;
    let lhs = cpu.a;
    let (result, carry) = lhs.overflowing_sub(value);
