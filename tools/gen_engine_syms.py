#!/usr/bin/env python3
"""Generate src/engine/sym.rs: WRAM (banks 0-1) and HRAM symbol addresses from
scratch/pokecrystal/pokecrystal.sym, plus the ROM tables the engine reads.

Usage: python3 tools/gen_engine_syms.py
writes src/engine/sym.rs (RAM symbols) and src/engine/rsym.rs (ROM labels).
"""
import re
import glob
# Every ROM label the battle code mentions (texts, data tables, ...).
SOURCES = (glob.glob('scratch/pokecrystal/engine/battle/**/*.asm', recursive=True)
           + glob.glob('scratch/pokecrystal/engine/items/*.asm')
           + glob.glob('scratch/pokecrystal/home/*.asm')
           + glob.glob('scratch/pokecrystal/data/moves/*.asm')
           + glob.glob('scratch/pokecrystal/data/battle/**/*.asm', recursive=True)
           + glob.glob('scratch/pokecrystal/data/text/battle.asm')
           + glob.glob('scratch/pokecrystal/engine/events/happiness_egg.asm')
           + glob.glob('scratch/pokecrystal/engine/pokemon/*.asm')
           + glob.glob('scratch/pokecrystal/engine/smallflag.asm')
           + glob.glob('scratch/pokecrystal/data/events/*.asm')
           + glob.glob('scratch/pokecrystal/data/pokemon/*.asm'))
MENTIONED = set()
for path in SOURCES:
    for line in open(path, encoding='utf-8', errors='replace'):
        code = line.split(';', 1)[0]
        MENTIONED.update(re.findall(r'\b([A-Z_][A-Za-z0-9_]*)\b', code))
ROM_TABLES = []

def const_name(sym):
    # wBattleMonHP -> W_BATTLE_MON_HP ; hBattleTurn -> H_BATTLE_TURN
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', sym)
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.upper().replace('.', '_')

wram, hram, rom = {}, {}, {}
for line in open('scratch/pokecrystal/pokecrystal.sym'):
    m = re.match(r'^([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$', line.strip())
    if not m:
        continue
    bank, addr, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3)
    if '.' in name:
        continue
    if 0xc000 <= addr <= 0xcfff and bank == 0:
        wram.setdefault(addr, []).append(name)
    elif 0xd000 <= addr <= 0xdfff and bank == 1:
        wram.setdefault(addr, []).append(name)
    elif 0xff80 <= addr <= 0xfffe and bank == 0:
        hram.setdefault(addr, []).append(name)
    elif addr < 0x8000 and name in MENTIONED and name not in rom:
        rom[name] = (bank, addr)

import sys
out = open('src/engine/sym.rs', 'w')
def print(*args, **kw):
    kw.setdefault('file', out)
    __builtins__.print(*args, **kw)
print("//! Symbol addresses from pret/pokecrystal's `pokecrystal.sym`. Generated by")
print("//! `tools/gen_engine_syms.py`; do not edit by hand.")
print("#![allow(dead_code)]")
print()
print("// WRAM banks 0 and 1 (0xc000..=0xdfff).")
seen = set()
for addr in sorted(wram):
    for name in wram[addr]:
        c = const_name(name)
        if c in seen:
            continue
        seen.add(c)
        print(f"pub const {c}: u16 = {addr:#06x};")
print()
print("// HRAM.")
for addr in sorted(hram):
    for name in hram[addr]:
        c = const_name(name)
        if c in seen:
            continue
        seen.add(c)
        print(f"pub const {c}: u16 = {addr:#06x};")
print()
print("/// Every WRAM/HRAM symbol, sorted by address, for naming diffs.")
print("pub const RAM_SYMBOLS: &[(u16, &str)] = &[")
for addr in sorted(list(wram) + list(hram)):
    names = (wram.get(addr) or hram.get(addr))
    print(f"    ({addr:#06x}, \"{names[0]}\"),")
print("];")
print()
print("/// The symbol covering `addr` and the offset into it, e.g. `wBattleMon+16`.")
print("pub fn ram_name(addr: u16) -> String {")
print("    let i = RAM_SYMBOLS.partition_point(|&(a, _)| a <= addr);")
print("    if i == 0 { return format!(\"{addr:#06x}\"); }")
print("    let (base, name) = RAM_SYMBOLS[i - 1];")
print("    if base == addr { name.to_string() } else { format!(\"{name}+{}\", addr - base) }")
print("}")
print()
out.close()
out = open('src/engine/rsym.rs', 'w')
print("//! ROM labels the battle code mentions (texts, data tables, routines), as")
print("//! flat offsets into the ROM image. Generated by `tools/gen_engine_syms.py`")
print("//! from pret/pokecrystal's `pokecrystal.sym`; do not edit by hand. Use")
print("//! qualified (`rsym::MOVES`): names can clash with game constants.")
print("#![allow(dead_code)]")
print()
for name in sorted(rom):
    c = const_name(name)
    bank, addr = rom[name]
    flat = addr if bank == 0 else bank * 0x4000 + (addr - 0x4000)
    print(f"pub const {c}: usize = {flat:#08x}; // {bank:02x}:{addr:04x} {name}")

out.close()
