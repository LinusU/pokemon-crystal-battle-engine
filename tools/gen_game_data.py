# `ReadTrainerParty` walks from the class's group to the `id`th party, so an
# id past the class's parties reads into the next class's: the parties are one
# list in ROM order, and each class points at its first.

def crystal_parties():
    GROUPS = label("TrainerGroups")
    GROUPS_BANK = bank("TrainerGroups")


    def is_party(q):
        """Whether a party (name, valid type, mons, $ff) starts at `q`."""
        n = 0
        while ROM[q] != 0x50:
            q += 1
            n += 1
            if n > 16:
                return False
        q += 1
        if ROM[q] > 3:
            return False
        return True
    group_starts = {}
    for c in range(256):
        ptr = w(GROUPS + 2 * idx(c))
        if 0x4000 <= ptr < 0x8000:
            group_starts[c] = flat(GROUPS_BANK, ptr)
    first = group_starts[1]
    parties = []
    party_at = {}
    p = first
    while True:
        party_at[p] = len(parties)
        q = p
        name_bytes = []
        while ROM[q] != 0x50:
            name_bytes.append(ROM[q])
            q += 1
        q += 1
        kind = ROM[q]
        q += 1
        mons = []
        while ROM[q] != 0xFF:
            level, species = ROM[q], ROM[q + 1]
            q += 2
            item = moves = None
            if kind in (2, 3):
                item = ROM[q]
                q += 1
            if kind in (1, 3):
                moves = list(ROM[q : q + 4])
                q += 4
            mons.append((level, species, item, moves))
        q += 1
        parties.append((decode(name_bytes), kind, mons))
        p = q
        if p >= label("MysticalmanGroup") and not is_party(p):
            break

    firsts = []
    for c in range(256):
        st = group_starts.get(c)
        firsts.append(str(party_at[st]) if st in party_at else "u16::MAX")
    emit_parties([{"name": name, "kind": kind, "mons": [{"level": level, "species": species, "item": item, "moves": moves} for level, species, item, moves in mons]} for name, kind, mons in parties], firsts)


def rust_option(value, fmt=str):
    return "None" if value is None else f"Some({fmt(value)})"


def rust_mon(m):
    return (f"TrainerMon {{ level: {m['level']}, species: {m['species']}, item: {rust_option(m.get('item'))}, "
            f"moves: {rust_option(m.get('moves'))}, nickname: {rust_option(m.get('nickname'), rust_str)}, "
            f"dvs: {rust_option(m.get('dvs'))}, stat_exp: {rust_option(m.get('stat_exp'))}, "
            f"happiness: {rust_option(m.get('happiness'))} }}")


def emit_parties(parties, firsts):
    """`TRAINER_PARTIES` (`parties`: dicts of name, kind, mons and stages, in
    the original's order) and `TRAINER_CLASS_FIRST_PARTY` (`firsts`)."""
    emit("static TRAINER_PARTIES: &[TrainerParty] = &[")
    for party in parties:
        mons = ", ".join(rust_mon(m) for m in party["mons"])
        stages = ", ".join(f"TrainerStage {{ kind: {st['kind']}, mons: &[{', '.join(rust_mon(m) for m in st['mons'])}] }}"
                           for st in party.get("stages", []))
        emit(f"    TrainerParty {{ name: {rust_str(party['name'])}, kind: {party['kind']}, mons: &[{mons}], stages: &[{stages}] }},")
    emit("];")
    emit("")
    emit(f"static TRAINER_CLASS_FIRST_PARTY: &[u16] = &[{', '.join(firsts)}];")


def legacy_parties():
    """Crystal Legacy's `TrainerGroups` (`dba`: a bank, then an address) and
    parties, read the way its `ReadTrainerPartyPieces` reads them."""
    MOVES, ITEM, NICKNAME, DVS, STAT_EXP, VARIABLE, HAPPINESS = (1 << f for f in range(7))
    PERFECT_DV, PERFECT_STAT_EXP, MAX_HAPPINESS = 0x11, 0x1337, 0x42
    groups = label("TrainerGroups")
    group_labels = {flat(*SYM[name]) for name in SYM if name.endswith("Group") and "." not in name}
    starts = {}
    for c in range(1, 256):
        e = groups + 3 * idx(c)
        start = flat(ROM[e], w(e + 1))
        if start not in group_labels:
            break
        starts[c] = start
    order = sorted(set(starts.values()))

    def mons_of(kind, q):
        """The mons from `q` to a $ff (or a stage's $fe): (mons, end byte, next)."""
        mons = []
        while ROM[q] not in (0xFE, 0xFF):
            m = {"level": ROM[q], "species": ROM[q + 1]}
            q += 2
            if kind & NICKNAME:
                q += 1  # `ld a, [hli]` steps over a byte before the nickname.
                chars = []
                while True:
                    c = ROM[q]
                    q += 1
                    if c == 0x50:
                        break
                    chars.append(c)
                if chars:
                    m["nickname"] = decode(chars)
            if kind & DVS:
                m["dvs"] = [0xFF if b == PERFECT_DV else b for b in ROM[q : q + 2]]
                q += 2
            if kind & STAT_EXP:
                exp = []
                for _ in range(5):
                    lo, hi = ROM[q], ROM[q + 1]
                    # Stored byte for byte in the (big-endian) party struct.
                    exp.append(0xFFFF if lo | hi << 8 == PERFECT_STAT_EXP else lo << 8 | hi)
                    q += 2
                m["stat_exp"] = exp
            if kind & HAPPINESS:
                m["happiness"] = 0xFF if ROM[q] == MAX_HAPPINESS else ROM[q]
                q += 1
            if kind & ITEM:
                m["item"] = ROM[q]
                q += 1
            if kind & MOVES:
                m["moves"] = list(ROM[q : q + 4])
                q += 4
            mons.append(m)
        return mons, ROM[q], q + 1

    parties = []
    party_at = {}
    for n, start in enumerate(order):
        end = order[n + 1] if n + 1 < len(order) and order[n + 1] // 0x4000 == start // 0x4000 else None
        q = start
        while end is None or q < end:
            name_end = q
            while ROM[name_end] != 0x50 and name_end - q <= 16:
                name_end += 1
            if ROM[name_end] != 0x50:
                break  # past the group's last party
            party = {"name": decode(ROM[q:name_end]), "kind": ROM[name_end + 1], "mons": [], "stages": []}
            party_at[q] = len(parties)
            q = name_end + 2
            if party["kind"] & VARIABLE:
                while True:
                    kind = ROM[q]
                    mons, last, q = mons_of(kind, q + 1)
                    party["stages"].append({"kind": kind, "mons": mons})
                    if last == 0xFF:
                        break
            else:
                party["mons"], last, q = mons_of(party["kind"], q)
                assert last == 0xFF, f"{party['name']}: a $fe outside a staged party"
            parties.append(party)
            if end is None and (q >= len(ROM) or ROM[q] in (0x00, 0xFF)):
                break
    firsts = [str(party_at[starts[c]]) if c in starts else "u16::MAX" for c in range(256)]
    emit_parties(parties, firsts)


