CHARMAP[0x4A] = "PKMN"  # "<PKMN>"
for i in range(26):
    CHARMAP[0x80 + i] = chr(ord("A") + i)
    CHARMAP[0xA0 + i] = chr(ord("a") + i)
for i in range(10):
    CHARMAP[0xF6 + i] = chr(ord("0") + i)


UNMAPPED = set()


def decode(bs, strict=False):
    out = ""
    for c in bs:
        if c == 0x50:
            break
        if strict and c not in CHARMAP:
            UNMAPPED.add(c)
        out += CHARMAP.get(c, "")
    return out


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def nth_string(bank_, addr, n):
    """GetNthString: skip `n` @-terminated strings from bank:addr."""
    for _ in range(n):
        while ROM[flat(bank_, addr)] != 0x50:
            addr += 1
        addr += 1
    return flat(bank_, addr)


