def flat(bank, addr):
    return addr if addr < 0x4000 else bank * 0x4000 + (addr - 0x4000)


def label(name):
    return flat(*SYM[name])


def bank(name):
    return SYM[name][0]


def b(off):
    return ROM[off]


def w(off):
    return ROM[off] | ROM[off + 1] << 8


def until_ff(off, size=1):
    """Entries of `size` bytes up to (not including) a first byte of $ff."""
    out = []
    while ROM[off] != 0xFF:
        out.append(tuple(ROM[off : off + size]) if size > 1 else ROM[off])
        off += size
    return out


