def evos_and_learnset(species):
    ptr = w(EVOS_PTRS + 2 * idx(species))
    if not 0x4000 <= ptr < 0x8000:
        return None, None
    start = flat(EVOS_BANK, ptr)
    # Evolutions, by structure.
    evos = []
    p = start
    ok = True
    while ROM[p] != 0:
        kind = ROM[p]
        if kind == EVOLVE_LEVEL:
            evos.append(f"Evolution::Level {{ level: {ROM[p+1]}, species: {ROM[p+2]} }}"); p += 3
        elif kind == EVOLVE_ITEM:
            evos.append(f"Evolution::Item {{ item: {ROM[p+1]}, species: {ROM[p+2]} }}"); p += 3
        elif kind == EVOLVE_TRADE:
            evos.append(f"Evolution::Trade {{ item: {ROM[p+1]}, species: {ROM[p+2]} }}"); p += 3
        elif kind == EVOLVE_HAPPINESS:
            evos.append(f"Evolution::Happiness {{ time: {ROM[p+1]}, species: {ROM[p+2]} }}"); p += 3
        elif kind == EVOLVE_STAT:
            evos.append(f"Evolution::Stat {{ level: {ROM[p+1]}, cmp: {ROM[p+2]}, species: {ROM[p+3]} }}"); p += 4
        else:
            ok = False
            break
        if len(evos) > 8:
            ok = False
            break
    # Learnset, as LearnLevelMoves / FillMoves find it: skip to the first 0.
    p = start
    while ROM[p] != 0:
        p += 1
    p += 1
    learn = []
    while ROM[p] != 0 and len(learn) < 128:
        learn.append((ROM[p], ROM[p + 1]))
        p += 2
    return (evos if ok else None), learn


def heavy_ball_weight(species):
    s = species & 0xFF
    hl = w(DEX_PTRS + 2 * idx(s))
    bank_ = POKEDEX_ENTRY_BANKS[((s << 2 | s >> 6) & 0xFF) & 3]

    def byte(a):
        a &= 0xFFFF
        return 0x50 if a >= 0x8000 else ROM[flat(bank_, a)]

    while True:
        a = byte(hl)
        hl = (hl + 1) & 0xFFFF
        if a == 0x50:
            break
    hl = (hl + 2) & 0xFFFF
    return byte(hl) | byte(hl + 1) << 8


