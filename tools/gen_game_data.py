"""Generate the typed game data the battle engine reads (`GameData`).

    python3 tools/gen_game_data.py [ROM] [SYM] > crates/crystal-battle/src/data/crystal.rs
    python3 tools/gen_game_data.py --game crystal-legacy LEGACY.gbc LEGACY.sym \\
        > crates/crystal-battle/src/data/crystal_legacy.rs

Defaults: `pokecrystal.gbc` and `scratch/pokecrystal/pokecrystal.sym`. Any
ROM built from a pokecrystal fork (with its own .sym) works the same way;
`--game` names the few things a fork changes that the ROM and .sym don't
say (see `GAMES`).

Every table is decoded the way the engine walks it, including what the
original reads past a table's end for out-of-range ids (see
`crates/crystal-battle/src/data/game.rs`).
"""

