def item_name(i):
    if i < TM01:
        return list_name(ITEM_NAME, i)
    a = i
    # GetTMHMNumber: one less for each unused item id at or before `a`.
    for gap in GAME["item_gaps"]:
        if i >= gap:
            a = (a - 1) & 0xFF
    a = (a - TM01 + 1) & 0xFF
    if i >= HM01:
        a = (a - NUM_TMS) & 0xFF
    b = 0xF6
    while a >= 10:
        a -= 10
        b += 1
    return ("HM" if i >= HM01 else "TM") + decode([b & 0xFF, (a + 0xF6) & 0xFF])


